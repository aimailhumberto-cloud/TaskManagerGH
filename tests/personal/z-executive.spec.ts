import { test, expect } from '@playwright/test';
test('focus/capacity and structured decision lifecycle persist on desktop and mobile', async ({ page }) => {
  expect((await page.request.post('/api/auth/login', { data: { email: 'humberto@local.test', password: 'preview-local-only' } })).ok()).toBeTruthy();
  await page.goto('/');
  await page.getByLabel('Captura rápida').fill('Executive browser test');
  await page.getByRole('button', { name: 'Capturar para hoy' }).click();
  await page.getByRole('button', { name: 'Editar Executive browser test' }).click();
  await page.getByLabel('Estimación de trabajo (minutos)').fill('80');
  await page.getByLabel('Prioridad', { exact: true }).selectOption('High');
  await page.getByLabel('Motivo del cambio').fill('Test estimate');
  await page.getByRole('button', { name: 'Guardar cambios' }).click();
  await expect(page.getByRole('status')).toHaveText('Cambios guardados.');
  await page.getByText('Elegir focos y capacidad', { exact: true }).click();
  const plan = page.getByRole('form', { name: 'Plan del día' });
  await plan.getByRole('spinbutton').fill('60');
  await plan.getByRole('checkbox', { name: /Executive browser test/ }).check();
  await plan.getByRole('button', { name: 'Guardar plan del día' }).click();
  await expect(page.getByRole('region', { name: 'Capacidad del día' })).toContainText('Sobrecarga conocida: 20 min');
  await page.reload();
  await expect(page.getByRole('region', { name: 'Capacidad del día' })).toContainText('60 min');
  await page.getByRole('button', { name: 'Preparar decisión' }).click();
  const form = page.getByRole('form', { name: 'Editar decisión' });
  await form.getByLabel('Empresa de la decisión').selectOption('local-personal');
  await form.getByLabel('Pregunta para decidir').fill('Decision browser test');
  await form.getByLabel('Estado de decisión').selectOption('Ready');
  await form.getByLabel('Motivo de decisión o cambio').fill('Test validation');
  await form.getByRole('button', { name: 'Guardar decisión' }).click();
  await expect(page.locator('.hb-workspace').getByRole('alert')).toContainText('dos alternativas');
  await form.getByLabel('Alternativas, una por línea').fill('Option A\nOption B');
  await form.getByLabel('Evidencia y contexto').fill('Isolated evidence');
  await form.getByLabel('Estado de decisión').selectOption('Decided');
  await form.getByLabel('Resultado aprobado por Humberto').fill('Option A approved only in test');
  await form.getByRole('button', { name: 'Guardar decisión' }).click();
  const card = page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Decision browser test' }) });
  await expect(card).toContainText('Decidida');
  await card.getByRole('button', { name: 'Revisar decisión' }).click();
  await form.getByLabel('Estado de decisión').selectOption('Preparing');
  await form.getByLabel('Motivo de decisión o cambio').fill('Reopen isolated decision');
  await form.getByRole('button', { name: 'Guardar decisión' }).click();
  await card.getByText('Alternativas, evidencia e historial').click();
  page.once('dialog', dialog => dialog.accept('Restore test'));
  await card.getByRole('button', { name: 'Restaurar decisión a revisión 1' }).click();
  await expect(card).toContainText('Decidida');
  await page.reload();
  await expect(card).toContainText('Option A approved only in test');
  await page.goto('/buscar');
  await page.getByLabel('Buscar tareas, proyectos y evidencias').fill('Decision browser test');
  await expect(page.getByRole('heading', { name: 'Decision browser test' })).toBeVisible();
  for (const url of ['/', '/empresas', '/agenda', '/buscar']) {
    await page.setViewportSize({ width: 390, height: 844 }); await page.goto(url);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  }
});
