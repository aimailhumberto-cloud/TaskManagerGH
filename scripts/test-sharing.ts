import * as fs from 'fs'; import * as os from 'os'; import * as path from 'path';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'share-'));
const pv = path.join(root, 'vault'); fs.mkdirSync(pv, { recursive: true });
const note = (dir: string, id: string, extra: string, body: string) => fs.writeFileSync(path.join(dir, id + '.md'), `---\nid: ${id}\ntitle: Ficha ${id}\ntype: person\n${extra}\n---\n${body}\n`);
note(pv, 'hb-privada', '', 'SECRETO-HB'); note(pv, 'hb-publica', 'visibility: public', 'PUBLICO-HB'); note(pv, 'hb-para-ana', 'visibility: shared\nshared_with: [local-2]', 'SOLO-ANA-DE-HB'); note(pv, 'hb-rara', 'visibility: todos', 'VALOR-RARO');
process.env.SMJ_VAULT_PATH = pv; process.env.LOCAL_ACCOUNTS_FILE = path.join(root, 'accounts', 'accounts.json'); process.env.AGENT_KEYS_FILE = path.join(root, 'accounts', 'k.json'); process.env.SESSION_SECRET = '0123456789abcdef0123456789abcdef';
import * as B from '../src/lib/brains';
import * as Sh from '../src/lib/sharing';
import { runInBrain } from '../src/lib/brainContext';
import { createAccount } from '../src/lib/localAccounts';
import { createKey } from '../src/lib/agentKeys';
import { encryptSession } from '../src/lib/session';
let fail = 0;
const eq = (n: string, a: unknown, b: unknown) => { if (JSON.stringify(a) !== JSON.stringify(b)) { fail++; console.error('FALLA', n, JSON.stringify(a), '!=', JSON.stringify(b)); } };
const hb = createAccount({ email: 'hb@t.co', name: 'HB', role: 'Owner', password: 'Clave-larga-123', createdBy: 'setup' });
const ana = createAccount({ email: 'ana@t.co', name: 'Ana', role: 'Miembro', password: 'Clave-larga-123', createdBy: hb.id });
const luis = createAccount({ email: 'luis@t.co', name: 'Luis', role: 'Miembro', password: 'Clave-larga-123', createdBy: hb.id });
const av = B.ensureBrain(ana.id, 'Ana')!, lv = B.ensureBrain(luis.id, 'Luis')!;
note(av, 'ana-privada', '', 'SECRETO-ANA'); note(av, 'ana-para-luis', 'visibility: shared\nshared_with: [local-3]', 'DE-ANA-A-LUIS');
const ids = (r: Sh.SharedNode[]) => r.map(x => x.id).sort();
eq('Ana ve de otros', ids(Sh.querySharedNodes(ana.id)), ['hb-para-ana', 'hb-publica']);
eq('Luis ve de otros', ids(Sh.querySharedNodes(luis.id)), ['ana-para-luis', 'hb-publica']);
eq('HB ve de otros', ids(Sh.querySharedNodes('hb')), []);
const all = JSON.stringify([Sh.querySharedNodes(ana.id), Sh.querySharedNodes(luis.id), Sh.querySharedNodes('hb'), Sh.querySharedNodes('desconocido')]);
eq('nunca sale lo privado', /SECRETO|VALOR-RARO/.test(all), false);
eq('desconocido solo público', ids(Sh.querySharedNodes('desconocido')), ['hb-publica']);
eq('búsqueda', ids(Sh.querySharedNodes(ana.id, 'solo-ana')), ['hb-para-ana']);
eq('búsqueda no encuentra privado', ids(Sh.querySharedNodes(ana.id, 'SECRETO')), []);
// cambiar visibilidad
const anaCtx = { brainId: ana.id, vaultPath: av, primary: false };
eq('compartir con inexistente', runInBrain(anaCtx, () => Sh.setVisibility(av, 'ana-privada', 'shared', ['local-999'])).ok, false);
eq('valor inválido', runInBrain(anaCtx, () => Sh.setVisibility(av, 'ana-privada', 'todos', [])).ok, false);
eq('ficha ajena', runInBrain(anaCtx, () => Sh.setVisibility(av, 'hb-privada', 'public', [])).ok, false);
eq('HB sigue privada', fs.readFileSync(path.join(pv, 'hb-privada.md'), 'utf8').includes('public'), false);
eq('hacer pública', runInBrain(anaCtx, () => Sh.setVisibility(av, 'ana-privada', 'public', [])).ok, true);
eq('ahora Luis la ve', ids(Sh.querySharedNodes(luis.id)).includes('ana-privada'), true);
eq('volver a privada', runInBrain(anaCtx, () => Sh.setVisibility(av, 'ana-privada', 'private', [])).ok, true);
eq('ya no', ids(Sh.querySharedNodes(luis.id)).includes('ana-privada'), false);
// cerebro de la compañía
const H = (o: Record<string, string> = {}) => ({ get: (n: string) => o[n.toLowerCase()] ?? null });
const tok = (a: any) => encryptSession({ userId: a.id, personId: a.id, email: a.email, role: a.role, brain: B.brainIdForAccount(a), createdAt: new Date().toISOString() });
const res = (a: any, view?: string) => B.resolveBrain({ sessionToken: tok(a), brainView: view, headers: H(), path: '/x', method: 'GET' }) as any;
eq('sin compañía, vista ignorada', res(ana, 'compania').ctx.brainId, ana.id);
B.ensureBrain(B.COMPANY_BRAIN_ID, 'la compañía');
eq('Ana compañía solo lectura', [res(ana, 'compania').ctx.brainId, res(ana, 'compania').ctx.readOnly, res(ana, 'compania').ctx.ownBrainId], ['compania', true, ana.id]);
eq('HB compañía edita', [res(hb, 'compania').ctx.brainId, res(hb, 'compania').ctx.readOnly], ['compania', false]);
eq('compañía no es principal', res(hb, 'compania').ctx.primary, false);
const k = createKey(ana.id, 'Agente', 'escribir');
const viaKey = B.resolveBrain({ headers: H({ 'x-agent-key': k.key, 'x-brain': 'compania' }), path: '/x', method: 'GET' }) as any;
eq('agente compañía siempre solo lectura', [viaKey.ctx.brainId, viaKey.ctx.readOnly], ['compania', true]);
eq('agente x-brain ajeno ignorado', (B.resolveBrain({ headers: H({ 'x-agent-key': k.key, 'x-brain': 'hb' }), path: '/x', method: 'GET' }) as any).ctx.brainId, ana.id);
eq('compañía en la lista', B.listBrains().some(b => b.brainId === 'compania'), true);
eq('compañía no aparece como ajeno', Sh.querySharedNodes(ana.id).some(x => x.brainId === 'compania'), false);
if (fail) { console.error(fail + ' fallas'); process.exit(1); } console.log('compartir entre cerebros: todo ok');
