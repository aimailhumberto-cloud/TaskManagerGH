// Pruebas de la fase 1: diario, deshacer, todo o nada, bitácora y estado actual. Uso: npm run test:journal
import * as fs from 'fs'; import * as os from 'os'; import * as path from 'path';
import { withChange, trackBefore, readJournal, undoChange, rollbackCurrent } from '../src/lib/journal';
import { appendLog, setState, logLine } from '../src/lib/noteLog';
import { stampUpdated } from '../src/lib/vaultFiles';
let fails = 0; const eq = (m: string, a: unknown, b: unknown) => { const ok = JSON.stringify(a) === JSON.stringify(b); console.log(ok ? '  ok ' : 'FALLÓ', m, ok ? '' : `${JSON.stringify(a)} != ${JSON.stringify(b)}`); if (!ok) fails++; };
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'jr-')); const vault = path.join(root, 'vault'); fs.mkdirSync(vault);
const f = path.join(vault, 'A.md'); fs.writeFileSync(f, '---\nid: a\ntitle: Ficha A\nx: 1\n---\nHola\n');
const write = (p: string, c: string) => { trackBefore(p); fs.writeFileSync(p, c); };
(async () => {
  const { entry } = await withChange(vault, { actor: 'prueba', action: 'editar' }, () => write(f, '---\nid: a\ntitle: Ficha A\nx: 2\n---\nHola\n'));
  eq('entrada en el diario', !!entry, true);
  eq('campo cambiado', entry!.files[0].fields, ['x']);
  eq('resumen legible', entry!.summary, 'Ficha A: x');
  const { entry: none } = await withChange(vault, {}, () => write(f, fs.readFileSync(f, 'utf8')));
  eq('sin cambio real, sin entrada', none, null);
  const r = await undoChange(vault, entry!.id, { actor: 'prueba' });
  eq('deshacer', r.ok, true); eq('vuelve x: 1', /x: 1/.test(fs.readFileSync(f, 'utf8')), true);
  eq('marcado como deshecho', !!readJournal(vault).find(e => e.id === entry!.id)?.undoneAt, true);
  eq('no se deshace dos veces', (await undoChange(vault, entry!.id, { actor: 'prueba' })).ok, false);
  const { entry: e2 } = await withChange(vault, {}, () => write(f, 'cambio 2'));
  fs.writeFileSync(f, 'otro cambio por fuera');
  eq('no deshace si cambió después', (await undoChange(vault, e2!.id, {})).ok, false);
  const g = path.join(vault, 'B.md');
  await withChange(vault, {}, () => { write(g, 'nuevo'); write(f, 'tocado'); eq('todo o nada: devuelve 2', rollbackCurrent(), 2); });
  eq('todo o nada: B no existe', fs.existsSync(g), false); eq('todo o nada: A como estaba', fs.readFileSync(f, 'utf8'), 'otro cambio por fuera');
  const body = '# MEDIMEX\n\nIntro.\n\n## Datos\n\n- a\n';
  const s1 = setState(body, 'Vigente: lunes 16.');
  eq('estado actual debajo de la intro', s1.indexOf('Intro.') < s1.indexOf('## Estado actual') && s1.indexOf('## Estado actual') < s1.indexOf('## Datos'), true);
  eq('estado actual se reescribe', setState(s1, 'Vigente: martes 17.').match(/Vigente/g)!.length, 1);
  const l1 = appendLog(s1, logLine({ date: '2026-11-12', summary: 'uno' })), l2 = appendLog(l1, logLine({ date: '2026-11-13', summary: 'dos' }));
  eq('bitácora: la más nueva arriba', l2.indexOf('dos') < l2.indexOf('uno'), true);
  eq('bitácora: una sola sección', l2.match(/## Bitácora/g)!.length, 1);
  const fm: any = { updated_at: 'viejo', last_updated_at: 'viejo' }; stampUpdated(fm, { u: 'viejo', l: 'viejo' });
  eq('fecha única: ambas iguales', fm.updated_at === fm.last_updated_at && fm.updated_at !== 'viejo', true);
  const fm2: any = { last_updated_at: '2020-01-01T00:00:00Z' }; stampUpdated(fm2, { u: undefined, l: 'x' });
  eq('respeta la fecha que puso la acción', fm2.updated_at, '2020-01-01T00:00:00Z');
  fs.rmSync(root, { recursive: true, force: true });
  console.log(fails ? `${fails} fallas` : 'journal: todo ok'); process.exit(fails ? 1 : 0);
})();
