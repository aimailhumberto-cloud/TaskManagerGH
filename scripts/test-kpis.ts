import * as fs from 'fs'; import * as os from 'os'; import * as path from 'path';
import * as K from '../src/lib/kpis';
let fail = 0;
const eq = (n: string, a: unknown, b: unknown) => { if (JSON.stringify(a) !== JSON.stringify(b)) { fail++; console.error('FALLA', n, JSON.stringify(a), '!=', JSON.stringify(b)); } };
const throws = (n: string, f: () => unknown) => { try { f(); fail++; console.error('FALLA no lanzó', n); } catch {} };
const vault = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'kpi-')), 'vault'); fs.mkdirSync(vault);
throws('sin nombre', () => K.setKpi(vault, { value: 1 })); throws('sin valor', () => K.setKpi(vault, { name: 'Ventas' })); throws('valor texto', () => K.setKpi(vault, { name: 'Ventas', value: 'mucho' }));
const a = K.setKpi(vault, { name: 'Volumen Belice', value: '12,500', unit: 'cajas', target: 20000, period: 'Q4 2026' }, 'DOTS', new Date('2026-11-01T00:00:00Z'));
eq('crea', [a.id, a.value, a.unit, a.target, a.history.length], ['volumen-belice', 12500, 'cajas', 20000, 1]);
const b = K.setKpi(vault, { name: 'Volumen Belice', value: 14000, note: 'corte semanal' }, 'HB');
eq('actualiza por nombre', [b.value, b.history.length, b.history[1].by, b.unit, b.target], [14000, 2, 'HB', 'cajas', 20000]);
const c = K.setKpi(vault, { id: 'volumen-belice', target: 25000 });
eq('solo meta, sin punto nuevo', [c.target, c.history.length, c.value], [25000, 2, 14000]);
eq('quitar meta', K.setKpi(vault, { id: 'volumen-belice', target: null }).target, null);
throws('meta texto', () => K.setKpi(vault, { id: 'volumen-belice', target: 'alta' }));
for (let i = 0; i < 70; i++) K.setKpi(vault, { id: 'volumen-belice', value: i });
eq('historial acotado', K.listKpis(vault)[0].history.length, K.MAX_HISTORY);
for (let i = 1; i < K.MAX_KPIS; i++) K.setKpi(vault, { name: 'Indicador ' + i, value: i });
throws('tope', () => K.setKpi(vault, { name: 'Uno más', value: 1 }));
eq('borra', [K.deleteKpi(vault, 'indicador-1'), K.deleteKpi(vault, 'no-existe'), K.listKpis(vault).length], [true, false, K.MAX_KPIS - 1]);
eq('fuera de la bóveda', fs.readdirSync(vault).length, 0);
eq('ciudades por defecto', K.loadPrefs(vault), { home: null, hq: null });
eq('guarda casa', K.savePrefs(vault, { home: { name: 'Panamá', lat: 8.98, lon: -79.52 } }).home?.name, 'Panamá');
eq('inválida se descarta', K.savePrefs(vault, { hq: { name: 'X', lat: 999, lon: 0 } }).hq, null);
eq('casa se conserva', K.loadPrefs(vault).home?.lat, 8.98);
if (fail) { console.error(fail + ' fallas'); process.exit(1); } console.log('indicadores: todo ok');
