import assert from 'node:assert/strict';
import { mkdir, mkdtemp, writeFile, readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { randomBytes, randomUUID } from 'node:crypto';
import { capacity } from '../src/lib/executive';
import { createBackup, restoreBackup } from '../src/lib/localBackup';
async function main() {
  delete process.env.SUPABASE_URL; delete process.env.SUPABASE_SERVICE_ROLE_KEY;
  process.env.SESSION_SECRET = randomBytes(48).toString('hex');
  await mkdir('.local-data', { recursive: true });
  const dir = await mkdtemp(join('.local-data', 'executive-test-'));
  process.env.DATABASE_PATH = join(dir, 'db.json');
  await writeFile(process.env.DATABASE_PATH, JSON.stringify({ companies: [{ id: 'business', name: 'Fictional' }], people: [{ id: 'owner', name: 'Owner', role: 'Admin', avatar: '' }], tasks: [], projects: [], users: [], templates: [], agentQueue: [], smtpConfig: {} }));
  const { applyWorkspaceCommand } = await import('../src/services/workspaceService');
  const { dbService } = await import('../src/services/dbService');
  const actor = { userId: 'test', personId: 'owner', email: 'test@local.test', role: 'Admin', createdAt: new Date().toISOString() };
  const command = (action: string, fields: any, id?: string, expectedRevision?: number, requestId = randomUUID()) => applyWorkspaceCommand(actor, { action, fields, id, expectedRevision, requestId, reason: 'Isolated verification' }) as Promise<any>;
  const task = await command('createTask', { title: 'Executable', companyId: 'business', workDate: '2030-01-01', estimatedMinutes: 80, priority: 'High' });
  const unknown = await command('createTask', { title: 'No estimate', companyId: 'business', workDate: '2030-01-01' });
  const unconfirmed = await command('createTask', { title: 'Unverified', companyId: 'business', validationStatus: 'NeedsConfirmation' });
  await assert.rejects(command('saveDayPlan', { date: '2030-01-01', availableMinutes: 60, focusTaskIds: [unconfirmed.id] }, undefined, 0));
  const planFields = { date: '2030-01-01', availableMinutes: 60, focusTaskIds: [task.id] };
  const requestId = randomUUID();
  const plan = await command('saveDayPlan', planFields, undefined, 0, requestId);
  const bytes = await readFile(process.env.DATABASE_PATH, 'utf8');
  await command('saveDayPlan', planFields, undefined, 0, requestId);
  assert.equal(await readFile(process.env.DATABASE_PATH, 'utf8'), bytes);
  await assert.rejects(command('saveDayPlan', planFields, undefined, 0));
  let data = await dbService.readData();
  assert.deepEqual(capacity(data.tasks, 'owner', '2030-01-01', plan), { planned: 80, unknown: 1, available: 60, remaining: -20 });
  await assert.rejects(command('updateTask', { estimatedMinutes: -1 }, unknown.id, unknown.revision));
  const fields = { companyId: 'business', question: 'Which route?', alternatives: ['Route A', 'Route B'], evidence: 'Local test evidence', state: 'Preparing' };
  const decision = await command('createDecision', fields);
  await assert.rejects(command('updateDecision', { ...fields, state: 'Ready', missing: 'Open question' }, decision.id, decision.revision));
  const ready = await command('updateDecision', { ...fields, state: 'Ready' }, decision.id, decision.revision);
  await assert.rejects(command('updateDecision', { ...fields, state: 'Decided' }, decision.id, ready.revision));
  const decided = await command('updateDecision', { ...fields, state: 'Decided', outcome: 'Route A' }, decision.id, ready.revision);
  const reopened = await command('updateDecision', fields, decision.id, decided.revision);
  assert.equal(reopened.outcome, ''); assert.equal(reopened.history[2].snapshot.outcome, 'Route A');
  const restored = await command('restoreDecision', { revision: decided.revision }, decision.id, reopened.revision);
  assert.equal(restored.state, 'Decided'); assert.equal(restored.outcome, 'Route A'); assert.equal(restored.revision, 5);
  await assert.rejects(applyWorkspaceCommand({ ...actor, personId: 'other' }, { action: 'restoreDecision', id: decision.id, expectedRevision: 5, fields: { revision: 1 }, reason: 'Unauthorized test', requestId: randomUUID() }));
  const backup = await createBackup(process.env.DATABASE_PATH);
  await command('updateDecision', fields, decision.id, restored.revision);
  const restoredPath = join(dir, 'restored.json'); await restoreBackup(backup, restoredPath);
  data = JSON.parse(await readFile(restoredPath, 'utf8'));
  assert.equal(data.decisions?.[0].state, 'Decided'); assert.equal(data.dayPlans?.[0].revision, 1);
  console.log('PASS: isolated focuses/capacity, unverified exclusion, duplicate retry, stale revision, invalid estimate, decision requirements/reopen/restore/ownership and backup restoration.');
}
main().catch(error => { console.error(error); process.exitCode = 1; });
