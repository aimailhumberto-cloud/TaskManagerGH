import * as fs from 'fs'; import * as os from 'os'; import * as path from 'path';
process.env.LOCAL_ACCOUNTS_FILE = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'acc-')), 'a', 'accounts.json');
import * as A from '../src/lib/localAccounts';
let fail = 0;
const eq = (n: string, a: unknown, b: unknown) => { if (a !== b) { fail++; console.error('FALLA', n, a, '!=', b); } };
const throws = (n: string, f: () => unknown, status?: number) => { try { f(); fail++; console.error('FALLA no lanzó', n); } catch (e: any) { if (status && e.status !== status) { fail++; console.error('FALLA estado', n, e.status); } } };
eq('sin gerentes', A.hasManager(), false);
throws('clave corta', () => A.createAccount({ email: 'a@b.co', name: 'Ana', role: 'Owner', password: 'corta', createdBy: 'setup' }));
throws('clave simple', () => A.createAccount({ email: 'a@b.co', name: 'Ana', role: 'Owner', password: 'aaaaaaaaaaaaaa', createdBy: 'setup' }));
throws('correo malo', () => A.createAccount({ email: 'ab', name: 'Ana', role: 'Owner', password: 'Clave-larga-123', createdBy: 'setup' }));
throws('rol malo', () => A.createAccount({ email: 'a@b.co', name: 'Ana', role: 'Dios', password: 'Clave-larga-123', createdBy: 'setup' }));
const owner = A.createAccount({ email: 'HB@Test.com ', name: 'HB', role: 'Owner', password: 'Clave-larga-123', createdBy: 'setup' });
eq('id', owner.id, 'local-1'); eq('correo normalizado', owner.email, 'hb@test.com');
eq('sin hash en público', 'hash' in owner || 'salt' in owner, false);
eq('listar sin hash', JSON.stringify(A.listAccounts()).includes('"hash"'), false);
eq('archivo permisos', (fs.statSync(process.env.LOCAL_ACCOUNTS_FILE!).mode & 0o077), 0);
throws('duplicado', () => A.createAccount({ email: 'hb@test.com', name: 'Xx', role: 'Miembro', password: 'Clave-larga-123', createdBy: 'x' }), 409);
eq('login ok', A.authenticateLocal('hb@test.com', 'Clave-larga-123')?.id, 'local-1');
eq('login mayúsculas', A.authenticateLocal('HB@TEST.COM', 'Clave-larga-123')?.id, 'local-1');
eq('login mala', A.authenticateLocal('hb@test.com', 'otra-clave-larga'), null);
eq('login inexistente', A.authenticateLocal('no@test.com', 'Clave-larga-123'), null);
eq('lastLogin', !!A.getAccount('local-1')?.lastLoginAt, true);
const ger = A.createAccount({ email: 'g@test.com', name: 'Gerente', role: 'Gerente', password: 'Gerente-clave-12', createdBy: 'local-1' });
const mie = A.createAccount({ email: 'm@test.com', name: 'Miembro', role: 'Miembro', password: 'Miembro-clave-12', createdBy: 'local-3'.replace('3', '2') });
eq('hay gerente', A.hasManager(), true);
throws('gerente no crea admin por rol', () => A.updateAccount(mie.id, { role: 'Admin' }, { id: ger.id, role: 'Gerente' }), 403);
throws('gerente no toca owner', () => A.updateAccount('local-1', { isActive: false }, { id: ger.id, role: 'Gerente' }), 403);
eq('gerente cambia miembro', A.updateAccount(mie.id, { role: 'Solo lectura' }, { id: ger.id, role: 'Gerente' }).role, 'Solo lectura');
throws('no desactivarse', () => A.updateAccount(ger.id, { isActive: false }, { id: ger.id, role: 'Gerente' }));
A.updateAccount(mie.id, { isActive: false }, { id: ger.id, role: 'Gerente' });
eq('inactivo no entra', A.authenticateLocal('m@test.com', 'Miembro-clave-12'), null);
A.updateAccount(mie.id, { newPassword: 'Nueva-clave-largaX' }, { id: ger.id, role: 'Gerente' });
eq('reset marca cambio', A.getAccount(mie.id)?.mustChange, true);
A.updateAccount(mie.id, { isActive: true }, { id: ger.id, role: 'Gerente' });
eq('entra con nueva', A.authenticateLocal('m@test.com', 'Nueva-clave-largaX')?.id, mie.id);
eq('no entra con vieja', A.authenticateLocal('m@test.com', 'Miembro-clave-12'), null);
throws('cambio con actual mala', () => A.changeOwnPassword(mie.id, 'mala-mala-mala', 'Otra-clave-larga-1'), 403);
A.changeOwnPassword(mie.id, 'Nueva-clave-largaX', 'Otra-clave-larga-1');
eq('mustChange limpio', A.getAccount(mie.id)?.mustChange, false);
A.updateAccount(ger.id, { isActive: false }, { id: 'local-1', role: 'Owner' });
throws('último gestor', () => A.updateAccount('local-1', { role: 'Miembro' }, { id: 'local-1', role: 'Owner' }));
eq('rol intacto tras error', A.getAccount('local-1')?.role, 'Owner');
eq('token ok', A.setupTokenValid('abcdefghijklmnopq', 'abcdefghijklmnopq'), true);
eq('token malo', A.setupTokenValid('abcdefghijklmnopX', 'abcdefghijklmnopq'), false);
eq('token corto', A.setupTokenValid('abc', 'abc'), false);
eq('token sin config', A.setupTokenValid('abcdefghijklmnopq', ''), false);
if (fail) { console.error(fail + ' fallas'); process.exit(1); } console.log('local accounts: todo ok');
