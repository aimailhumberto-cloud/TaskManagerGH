/** Pruebas de la entrada tolerante (sin servidor). Uso: npx tsx scripts/test-intake.ts */
import { parseBody, normalizeBody, consultIsRequest, redact } from '../src/lib/cerebro/intake';
let ok = 0, bad = 0; const t = (n: string, c: boolean, extra = '') => { c ? ok++ : (bad++, console.log('✗', n, extra)); };
const N = (o: Record<string, unknown>) => normalizeBody(o);
t('JSON normal', parseBody('{"action":"pedir","text":"hola"}').body.action === 'pedir');
t('texto plano → text', parseBody('Registra a Luisa').body.text === 'Registra a Luisa');
t('formulario', parseBody('action=pedir&text=hola', 'application/x-www-form-urlencoded').body.text === 'hola');
t('JSON con coma final', parseBody('{"action":"pedir","text":"x",}').body.text === 'x');
t('JSON con comillas simples', parseBody("{'action':'pedir','text':'x'}").body.action === 'pedir');
t('JSON dentro de texto', parseBody('{"input":"{\\"text\\":\\"x\\"}"}').body.input !== undefined);
t('vacío', Object.keys(parseBody('').body).length === 0);
t('alias ask→pedir', N({ action: 'ask', text: 'x' }).body.action === 'pedir');
t('alias query→consultar', N({ action: 'query', q: 'x' }).body.action === 'consultar');
t('acción desconocida con texto → pedir', N({ action: 'zzz', text: 'x' }).body.action === 'pedir');
t('sin acción con texto → pedir', N({ text: 'x' }).body.action === 'pedir');
t('sin acción con q → consultar', N({ q: 'x' }).body.action === 'consultar');
t('sin acción con id+text → responder', N({ id: 'a', text: 'x' }).body.action === 'responder');
t('campo message→text', N({ action: 'pedir', message: 'x' }).body.text === 'x');
t('campo expediente→md', N({ action: 'pedir', text: 'x', expediente: '# a' }).body.md === '# a');
t('wrapper arguments (texto JSON)', N({ arguments: '{"action":"pedir","text":"x"}' }).body.text === 'x');
t('wrapper input', N({ input: { action: 'pedir', text: 'x' } }).body.action === 'pedir');
t('array → texto', N({ action: 'pedir', text: ['a', 'b'] }).body.text === 'a\nb');
t('acción con mayúsculas', N({ action: 'Pedir', text: 'x' }).body.action === 'pedir');
t('deja arreglos anotados', N({ action: 'ask', message: 'x' }).arreglos.length === 2);
t('sin nada → sin acción', !N({}).body.action);
t('consultar con md es pedido', consultIsRequest({ q: 'x', md: '# a' }, 'consulta'));
t('consultar con pregunta no es pedido', !consultIsRequest({ q: '¿Qué hay hoy?' }, 'pedido'));
t('consultar largo sin pregunta es pedido', consultIsRequest({ q: 'Registra a Luisa en el CRM' }, 'pedido'));
t('redact oculta llaves', JSON.stringify(redact({ apiKey: 'abc', x: { token: 'z' }, ok: 1 })).includes('abc') === false);
console.log(`${ok} bien, ${bad} mal`); process.exit(bad ? 1 : 0);
